#!/usr/bin/env python3
"""Write reports/team-coverage.md: which firms are covered, by whom, at what status.

Built only from contact frontmatter (firm, region, assigned_to, status). It never
reads or writes names, emails, phones, roles or History, so the output is safe to
list in share.txt. Region and assigned_to are optional: blank when a contact file
doesn't have them.

Usage: python3 scripts/coverage.py [--root PATH]
"""
import argparse, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join("reports", "team-coverage.md")
HEADER = "Generated by scripts/coverage.py, do not edit by hand. Check before contacting any firm."
SAFE_FIELDS = ("firm", "region", "assigned_to", "status")  # the only contact fields this script reads

def safe_fm(text):
    text = text.replace("\r\n", "\n")  # CRLF files (Windows) parse the same
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    d = {}
    for line in (m.group(1).splitlines() if m else []):
        if ":" in line:
            k, v = line.split(":", 1)
            if k.strip() in SAFE_FIELDS: d[k.strip()] = v.strip()
    return d

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--root", default=ROOT); a = ap.parse_args(); root = a.root
    rows = []
    cdir = os.path.join(root, "contacts")
    for fn in sorted(os.listdir(cdir)) if os.path.isdir(cdir) else []:
        if not fn.endswith(".md"): continue
        with open(os.path.join(cdir, fn), encoding="utf-8") as f:
            c = safe_fm(f.read())
        rows.append((c.get("firm", "") or "(firm blank)", c.get("region", ""), c.get("assigned_to", ""), c.get("status", "")))
    lines = [HEADER, "", "| Firm | Region | Owner | Status |", "|---|---|---|---|"]
    lines += [f"| {' | '.join(r)} |" for r in rows]
    os.makedirs(os.path.join(root, "reports"), exist_ok=True)
    with open(os.path.join(root, OUT), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(rows)} rows)")

if __name__ == "__main__":
    main()
